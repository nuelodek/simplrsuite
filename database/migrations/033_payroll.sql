CREATE TABLE IF NOT EXISTS payroll_profiles (
  company_id INT NOT NULL,
  staff_role VARCHAR(16) NOT NULL,
  staff_id INT NOT NULL,
  monthly_salary DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  monthly_allowances DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  bank_name VARCHAR(120) NOT NULL DEFAULT '',
  bank_code VARCHAR(20) NOT NULL DEFAULT '',
  account_name VARCHAR(160) NOT NULL DEFAULT '',
  account_number_ciphertext TEXT NOT NULL,
  updated_by INT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (company_id, staff_role, staff_id),
  KEY payroll_profiles_staff (staff_role, staff_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payroll_runs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id INT NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  pay_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  created_by INT NOT NULL,
  approved_by INT NULL DEFAULT NULL,
  approved_at DATETIME NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY payroll_runs_period (company_id, period_start, period_end),
  KEY payroll_runs_company_status (company_id, status, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payroll_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  company_id INT NOT NULL,
  run_id BIGINT UNSIGNED NOT NULL,
  staff_role VARCHAR(16) NOT NULL,
  staff_id INT NOT NULL,
  staff_name VARCHAR(160) NOT NULL,
  staff_email VARCHAR(255) NOT NULL DEFAULT '',
  bank_name VARCHAR(120) NOT NULL DEFAULT '',
  bank_code VARCHAR(20) NOT NULL DEFAULT '',
  account_name VARCHAR(160) NOT NULL DEFAULT '',
  account_number_ciphertext TEXT NOT NULL,
  paystack_recipient_code VARCHAR(80) NOT NULL DEFAULT '',
  basic_pay DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  allowances DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  bonus DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  paye DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  pension DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  nhf DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  other_deductions DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  net_pay DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  payout_status VARCHAR(20) NOT NULL DEFAULT 'not_started',
  payout_reference VARCHAR(100) NULL DEFAULT NULL,
  bank_payment_reference VARCHAR(100) NOT NULL DEFAULT '',
  provider_transfer_code_ciphertext TEXT NULL,
  paid_at DATETIME NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY payroll_items_staff (run_id, staff_role, staff_id),
  UNIQUE KEY payroll_items_reference (payout_reference),
  KEY payroll_items_company_run (company_id, run_id, id),
  KEY payroll_items_staff_history (company_id, staff_role, staff_id, run_id),
  CONSTRAINT payroll_items_run_fk FOREIGN KEY (run_id) REFERENCES payroll_runs (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
